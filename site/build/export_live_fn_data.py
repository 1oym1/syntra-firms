"""Write site/functions/live/sudan_data.mjs: the border and static mask the live Netlify Function needs.

The function filters NASA FIRMS public 24 h files to Sudan the way the app does (syntra.clean):
inside the country border, confidence MODIS >= 30 or VIIRS nominal/high, static-source cells dropped.

    python site/build/export_live_fn_data.py
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
from syntra import datapack  # noqa: E402
from syntra.clean import MASK_DEG, MODIS_CONF, country_shape  # noqa: E402

shape = country_shape("Sudan").simplify(0.005)
polys = list(shape.geoms) if shape.geom_type == "MultiPolygon" else [shape]
rings = [[[round(x, 4), round(y, 4)] for x, y in p.exterior.coords] for p in polys]
rings += [[[round(x, 4), round(y, 4)] for x, y in r.coords] for p in polys for r in p.interiors]
mask = [int(c) for c in datapack.load("Sudan")["static_mask"].mask_cell]
minx, miny, maxx, maxy = shape.bounds
out = {"rings": rings, "bbox": [round(minx, 3), round(miny, 3), round(maxx, 3), round(maxy, 3)],
       "mask": mask, "mask_deg": MASK_DEG, "modis_conf": MODIS_CONF}
dst = ROOT / "site" / "functions" / "live" / "sudan_data.mjs"
dst.write_text("// Generated by site/build/export_live_fn_data.py. Do not edit.\nexport default " + json.dumps(out, separators=(",", ":")) + ";\n")
print(f"wrote {dst} ({dst.stat().st_size // 1024} KB, {sum(map(len, rings))} border points, {len(mask)} mask cells)")
